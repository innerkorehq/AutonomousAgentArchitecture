"""`aaa mcp init` and `aaa mcp export`: write a project around a server configuration.

The generated project is PACKAGING, not logic: `server.py` is a fixed file that loads `server.<toml|json|yaml>` and compiles it with
`aaa.mcp`, so what the project does is decided by the configuration alone. Nothing a user types is ever written into Python source
(the files are static templates; user data lives only in the configuration, which is written from the validated spec), and no secret
value is ever written anywhere (only the names of the environment variables that hold them, in `.env.example`).

`.aaa-scaffold.json` records the options and a hash of each generated file, so `export --check` can tell you a file drifted from its
template and `export --update` can regenerate the files you have not touched."""

from __future__ import annotations

import hashlib
import json
import re
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from string import Template
from typing import Any

from aaa import __version__
from aaa.mcp.config import SpecError, spec_text
from aaa.mcp.spec import MCPSpec

MANIFEST = ".aaa-scaffold.json"
NAME = re.compile(r"^[a-z][a-z0-9_-]{0,62}$")
AAA_SERVER_MIN = (
    "0.2.0.dev0"  # the first aaa-server that serves everything the generator can configure
)
FORMATS = ("toml", "json", "yaml")
_ENV = re.compile(r"^(?:env:|\$\{)([A-Za-z_][A-Za-z0-9_]*)\}?$")


@dataclass(frozen=True)
class Options:
    name: str
    transport: str = "stdio"  # stdio | http
    docker: bool = True
    fmt: str = "toml"

    def validate(self) -> Options:
        if not NAME.match(self.name):
            raise SpecError(
                f"project name {self.name!r} must be lowercase letters, digits, '-' and '_' (starting with a letter)"
            )
        if self.transport not in ("stdio", "http"):
            raise SpecError("transport must be 'stdio' or 'http'")
        if self.fmt not in FORMATS:
            raise SpecError(f"format must be one of {FORMATS}")
        return self

    @property
    def config_name(self) -> str:
        return f"server.{'yaml' if self.fmt == 'yaml' else self.fmt}"


# -- what the spec needs from the environment -------------------------------------------------
def secret_names(spec: MCPSpec) -> list[str]:
    """Names (never values) of the environment variables the configuration refers to."""
    from aaa.mcp.clientconfig import env_names

    return env_names(spec)


