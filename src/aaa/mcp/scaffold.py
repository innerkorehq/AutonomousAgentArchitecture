_SERVER_STDIO = '''\
"""Runs the MCP server described by server.$ext. Generated by `aaa mcp init`; edit the configuration, not this file."""

import asyncio
from pathlib import Path

from aaa.mcp import acompile_spec, load_spec, serve_stdio

CONFIG = Path(__file__).with_name("server.$ext")


async def run() -> None:
    core = await acompile_spec(load_spec(CONFIG))
    if core.owns_engine and core.engine is not None:
        async with core.engine:
            await serve_stdio(core)
    else:
        await serve_stdio(core)


def main() -> None:
    asyncio.run(run())


if __name__ == "__main__":
    main()
'''

_SERVER_HTTP = '''\
"""Serves the MCP server described by server.$ext over HTTP with aaa-server. Generated by `aaa mcp init`.

Run:  aaa-server serve server:build --host 0.0.0.0 --port 8000      (put a TLS-terminating reverse proxy in front)
Auth: MCP_API_KEYS='{"<api key>": ["<tenant>", "<subject>"]}'. Callers' tenant and user come from the key, never from requests.
If the configuration has `agents`, wire your model and handlers onto `engine` below before it is used."""

import json
import os
from pathlib import Path

from aaa.mcp import acompile_spec, load_spec
from aaa.runtime import Engine
from aaa_server import ApiKeyAuthenticator, InMemoryRateLimiter, ServerConfig

CONFIG = Path(__file__).with_name("server.$ext")


async def build() -> ServerConfig:
    keys = json.loads(os.environ.get("MCP_API_KEYS", "{}"))
    if not keys:
        raise SystemExit("MCP_API_KEYS is empty: refusing to start a server nobody can authenticate to")
    engine = Engine()
    core = await acompile_spec(load_spec(CONFIG), engine=engine)
    return ServerConfig(
        engine=engine,
        authenticator=ApiKeyAuthenticator.from_keys({k: tuple(v) for k, v in keys.items()}),
        mcp=core,
        rate_limiter=InMemoryRateLimiter(per_second=10, burst=50),
    )
'''

