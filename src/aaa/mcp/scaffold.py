_GITIGNORE = ".env\n__pycache__/\n*.pyc\n"
_DOCKERIGNORE = ".env\n.git\n__pycache__/\ntests/\n"


def _hash(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def _version_range() -> tuple[str, str]:
    parts = __version__.split(".")
    try:
        major, minor = int(parts[0]), int(parts[1])
    except (ValueError, IndexError):
        return "0.3.0", "0.4"
    return __version__.split("+")[0], f"{major}.{minor + 1}" if major == 0 else f"{major + 1}.0"


def render(spec: MCPSpec, config_text: str, opts: Options) -> dict[str, str]:
    """Every file of the project, as {relative path: text}. The configuration file is included as given (it is the user's)."""
    opts.validate()
    secrets = secret_names(spec)
    http = opts.transport == "http"
    lo, hi = _version_range()
    extras = ",".join(["mcp", *(["mcp-config"] if opts.fmt == "yaml" else [])])
    extra_lines = f"aaa-server>={AAA_SERVER_MIN}\n" if http else ""
    run = (
        "aaa-server serve server:build --host 127.0.0.1 --port 8000"
        if http
        else "aaa mcp serve --config " + opts.config_name
    )
    notes = []
    if http:
        notes.append(
            'Set `MCP_API_KEYS=\'{"<api key>": ["<tenant>", "<subject>"]}\'` to say who may call it. The key decides the tenant and user.'
        )
    if spec.agents:
        notes.append(
            "The configuration has `agents`: wire your model and handlers onto the engine (`runtime.engine` in the configuration, or `server.py`) before using them."
        )
    if any(
        getattr(s, "type", "") == "objects" or getattr(s, "type", "") == "module"
        for s in spec.sources
    ):
        notes.append(
            "The configuration imports your code: keep the file writable only by you, and set `AAA_MCP_ALLOW_IMPORT=0` to refuse it where imports must not happen."
        )
    t = lambda tpl, **kw: Template(tpl).safe_substitute(**kw)
    files = {
        opts.config_name: config_text,
        "server.py": t(
            _SERVER_HTTP if http else _SERVER_STDIO, ext=opts.config_name.split(".", 1)[1]
        ),
        "tests/test_server.py": t(
            _TEST, secrets=repr(secrets), ext=opts.config_name.split(".", 1)[1]
        ),
        "requirements.txt": t(
            _REQUIREMENTS, version=__version__, extras=extras, lo=lo, hi=hi, extra_lines=extra_lines
        ),
        "README.md": t(
            _README,
            name=opts.name,
            version=__version__,
            config=opts.config_name,
            run=run,
            notes="\n\n".join(notes) + ("\n" if notes else ""),
        ),
        ".env.example": t(
            _ENV_EXAMPLE,
            lines="".join(f"{n}=\n" for n in [*secrets, *(["MCP_API_KEYS"] if http else [])]),
        ),
        ".gitignore": _GITIGNORE,
    }
    if opts.docker:
        files["Dockerfile"] = t(
            _DOCKERFILE_HTTP if http else _DOCKERFILE_STDIO, config=opts.config_name
        )
        files[".dockerignore"] = _DOCKERIGNORE
    return files


def config_text_for(spec: MCPSpec, opts: Options) -> str:
    """The configuration file's text: the spec as TOML/YAML/JSON (JSON has no comments, so it gets none)."""
    body = spec_text(spec, f".{opts.fmt}")
    if opts.fmt == "json":
        return body
    return f"# Generated by `aaa mcp init` (aaa {__version__}). This file is yours: edit it. Secrets are env: references only.\n{body}"


def write_project(
    dest: Path, files: dict[str, str], opts: Options, *, force: bool = False
) -> list[str]:
    """Write the project. Refuses to touch a non-empty directory (or overwrite a file) unless `force`."""
    dest = dest.resolve()
    if dest.exists() and any(dest.iterdir()) and not force:
        raise SpecError(
            f"{dest} is not empty; use --force to write into it (existing files are overwritten)"
        )
    written = []
    for rel, text in files.items():
        target = (dest / rel).resolve()
        target.relative_to(dest)  # a generated path can never leave the project directory
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
        written.append(rel)
    manifest = {
        "generator": f"aaa {__version__}",
        "options": {
            "name": opts.name,
            "transport": opts.transport,
            "docker": opts.docker,
            "fmt": opts.fmt,
        },
        "config": opts.config_name,
        "files": {rel: _hash(text) for rel, text in files.items() if rel != opts.config_name},
    }
    (dest / MANIFEST).write_text(json.dumps(manifest, indent=2) + "\n")
    return written


def _manifest(dest: Path) -> dict[str, Any]:
    try:
        return json.loads((dest / MANIFEST).read_text())
    except (OSError, ValueError):
        raise SpecError(
            f"{dest} has no {MANIFEST}: it was not generated by `aaa mcp init`"
        ) from None


def regenerate(dest: Path) -> tuple[dict[str, Any], dict[str, str]]:
    """(manifest, the files the CURRENT templates would produce from the project's own configuration)."""
    from aaa.mcp.config import load_spec

    m = _manifest(dest)
    o = m["options"]
    opts = Options(o["name"], o["transport"], o["docker"], o["fmt"]).validate()
    cfg = dest / m["config"]
    spec = load_spec(cfg, environ={})
    return m, render(spec, cfg.read_text(), opts)


def check_project(dest: Path) -> list[str]:
    """Problems: generated files that are missing or differ from their template."""
    m, fresh = regenerate(dest)
    problems = []
    for rel, text in fresh.items():
        if rel == m["config"]:
            continue
        f = dest / rel
        if not f.exists():
            problems.append(f"{rel}: missing")
        elif f.read_text() != text:
            problems.append(
                f"{rel}: differs from its template"
                + (
                    " (and was edited by hand)"
                    if _hash(f.read_text()) != m["files"].get(rel)
                    else " (the template changed)"
                )
            )
    return problems


def update_project(dest: Path) -> tuple[list[str], list[str]]:
    """Regenerate files you have not edited. Returns (rewritten, skipped because you edited them)."""
    m, fresh = regenerate(dest)
    rewritten, skipped = [], []
    for rel, text in fresh.items():
        if rel == m["config"]:
            continue
        f = dest / rel
        if f.exists() and _hash(f.read_text()) != m["files"].get(rel):
            if f.read_text() != text:
                skipped.append(rel)
            continue
        if not f.exists() or f.read_text() != text:
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_text(text)
            rewritten.append(rel)
        m["files"][rel] = _hash(text)
    m["generator"] = f"aaa {__version__}"
    (dest / MANIFEST).write_text(json.dumps(m, indent=2) + "\n")
    return rewritten, skipped


# -- the interactive generator ----------------------------------------------------------------------
def prompt_spec(
    ask: Callable[[str], str], say: Callable[[str], None]
) -> tuple[MCPSpec, Options, Path]:
    """Ask questions and build a spec. `ask(prompt) -> answer`, `say(text)`; injectable, so it is testable and scriptable."""

    def choose(question: str, options: list[str], default: str) -> str:
        while True:
            a = ask(f"{question} [{'/'.join(options)}] ({default}): ").strip().lower() or default
            if a in options:
                return a
            say(f"  please answer one of {options}")

    name = ""
    while not NAME.match(name):
        name = ask("Project name (lowercase, e.g. support-desk): ").strip()
        if not NAME.match(name):
            say("  use lowercase letters, digits, '-' and '_', starting with a letter")
    data: dict[str, Any] = {"server": {"name": name}, "sources": []}
    say("Add tool sources (leave the type empty to stop).")
    while True:
        kind = choose("  source type", ["objects", "module", "openapi", "done"], "done")
        if kind == "done":
            break
        if kind == "objects":
            data["sources"].append(
                {
                    "type": "objects",
                    "ref": ask("    module:attribute holding a ToolRegistry: ").strip(),
                }
            )
        elif kind == "module":
            data["sources"].append(
                {
                    "type": "module",
                    "module": ask("    module name (e.g. myapp.tools): ").strip(),
                    "allow": [
                        x
                        for x in ask(
                            "    functions to expose (comma separated, empty = its __all__): "
                        )
                        .replace(" ", "")
                        .split(",")
                        if x
                    ],
                }
            )
        else:
            doc = ask("    OpenAPI document (path or https URL): ").strip()
            hosts = [
                h
                for h in ask("    allowed API host(s), comma separated: ")
                .replace(" ", "")
                .split(",")
                if h
            ]
            src: dict[str, Any] = {"type": "openapi", "document": doc, "allowed_hosts": hosts}
            if choose("    does it need a bearer token?", ["yes", "no"], "no") == "yes":
                env = ask("    environment variable holding the token (e.g. API_TOKEN): ").strip()
                src["auth"] = {"scheme": "bearer", "secret": f"env:{env}"}
            data["sources"].append(src)
    transport = choose("Transport", ["stdio", "http"], "stdio")
    docker = choose("Generate a Dockerfile?", ["yes", "no"], "yes") == "yes"
    fmt = choose("Configuration format", list(FORMATS), "toml")
    dest = Path(ask(f"Directory to write ({name}): ").strip() or name)
    from aaa.mcp.config import load_spec

    spec = load_spec(data, environ={})
    return spec, Options(name, transport, docker, fmt).validate(), dest
